#!/usr/bin/env node
/**
 * Inlines `office/worker.ps1` into a TypeScript constant.
 *
 * Same reasoning as the Python worker: esbuild does not copy `.ps1` into the bundle, and
 * resolving a path relative to the bundle is the trap that once shipped a VSIX which could not
 * activate. Embedding the source and writing it out at runtime avoids both.
 *
 * `worker.ps1` stays the source of truth — edit it, then run this. `office.test.ts` fails if
 * the two drift, so a forgotten regeneration cannot ship.
 */
import fs from 'node:fs'
import path from 'node:path'

const SOURCE = path.join('packages', 'core', 'src', 'office', 'worker.ps1')
const TARGET = path.join('packages', 'core', 'src', 'office', 'workerSource.ts')

const script = fs.readFileSync(SOURCE, 'utf8')

const nonAscii = [...new Set([...script].filter((character) => character.charCodeAt(0) > 127))]
if (nonAscii.length > 0) {
  // Windows PowerShell 5.1 decodes a BOM-less .ps1 as ANSI. The runtime writes a BOM, but a
  // single stray character here has already cost one debugging round, so it is refused outright.
  console.error(`[office] refusing to inline: non-ASCII characters in worker.ps1 -> ${JSON.stringify(nonAscii)}`)
  process.exit(1)
}

const header = `// GENERATED by scripts/generate-office-worker.mjs — do not edit.
// Source of truth: src/office/worker.ps1. Run \`pnpm generate:office\` after changing it.

/** The PowerShell worker, written to disk at runtime by \`OfficeBridge\`. */
export const OFFICE_WORKER_SOURCE = ${JSON.stringify(script)}
`
fs.writeFileSync(TARGET, header, 'utf8')
console.log(`[office] inlined ${script.length} chars -> ${TARGET}`)
