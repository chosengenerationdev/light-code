#!/usr/bin/env node
/**
 * Inlines `worker/main.py` into a TypeScript constant.
 *
 * The worker has to exist as a real file on disk for Python to run it, but esbuild does not
 * copy `.py` into the bundle, and resolving a path relative to the bundle is precisely the
 * trap that once shipped a VSIX that could not activate. Embedding the source and writing it
 * out at runtime sidesteps both: nothing to copy, nothing to locate.
 *
 * `main.py` stays the source of truth — edit it, then run this. `python.test.ts` fails if
 * the two drift, so a forgotten regeneration cannot ship.
 */
import fs from 'node:fs'
import path from 'node:path'

const SOURCE = path.join('packages', 'core', 'src', 'python', 'worker', 'main.py')
const TARGET = path.join('packages', 'core', 'src', 'python', 'workerSource.ts')

const python = fs.readFileSync(SOURCE, 'utf8')
const header = `// GENERATED by scripts/generate-python-worker.mjs — do not edit.
// Source of truth: src/python/worker/main.py. Run \`pnpm generate:worker\` after changing it.

/** The worker script, written to disk at runtime by \`PythonManager\`. */
export const PYTHON_WORKER_SOURCE = ${JSON.stringify(python)}
`
fs.writeFileSync(TARGET, header, 'utf8')
console.log(`[worker] inlined ${python.length} chars -> ${TARGET}`)
