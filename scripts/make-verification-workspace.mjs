#!/usr/bin/env node
/**
 * Builds a small, known workspace for MANUAL_VERIFICATION.md.
 *
 * The checks reference specific files by name, and several depend on their exact contents —
 * the read-before-edit check needs a file worth editing, the redaction check needs a
 * planted secret, and the rollback check needs a real git repository so it can prove the
 * shadow git never touches the user's own.
 *
 * Rerunning replaces the workspace, so a botched run is one command away from a clean slate.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

const root = path.join(os.tmpdir(), 'light-code-verification')

const files = {
  '.gitignore': ['node_modules/', 'secrets/', '*.log', ''].join('\n'),

  'README.md': [
    '# Verification workspace',
    '',
    'Generated by `scripts/make-verification-workspace.mjs`. Safe to delete.',
    'Used by MANUAL_VERIFICATION.md — the checks reference these files by name.',
    '',
  ].join('\n'),

  'src/math.ts': [
    'export function add(a: number, b: number): number {',
    '  return a + b',
    '}',
    '',
    'export function subtract(a: number, b: number): number {',
    '  return a - b',
    '}',
    '',
    'export function multiply(a: number, b: number): number {',
    '  return a * b',
    '}',
    '',
  ].join('\n'),

  'src/greet.ts': ['export function greet(name: string): string {', "  return `hello, ${name}`", '}', ''].join('\n'),

  // Deliberately larger, so "read the largest one" has an unambiguous answer and so a
  // read of it is big enough to be worth superseding.
  'src/inventory.ts': [
    '/** Padded on purpose: the largest file in src, and large enough to be worth superseding. */',
    'export interface Item {',
    '  id: string',
    '  name: string',
    '  quantity: number',
    '}',
    '',
    ...Array.from({ length: 60 }, (_, i) => `export const ITEM_${i} = { id: '${i}', name: 'item ${i}', quantity: ${i} }`),
    '',
  ].join('\n'),

  // Gitignored, and referenced by the redaction check. Not a real credential — the values
  // are shaped to match what redact() looks for.
  'secrets/fake-credentials.env': [
    '# Planted for MANUAL_VERIFICATION.md check A6. Not a real credential.',
    'GATEWAY_KEY=corp-gateway-key-9f3a1c',
    'OPENAI_KEY=sk-verification0000000000000000',
    'AUTH_HEADER=Bearer eyJhbGciOiJIUzI1NiJ9.verification.signature',
    '',
  ].join('\n'),
}

await fs.rm(root, { recursive: true, force: true })
for (const [relative, contents] of Object.entries(files)) {
  const target = path.join(root, relative)
  await fs.mkdir(path.dirname(target), { recursive: true })
  await fs.writeFile(target, contents, 'utf8')
}

// A real repository, so check B2 can prove the shadow git left the user's own alone.
try {
  const git = (...args) => execFileSync('git', args, { cwd: root, stdio: 'ignore' })
  git('init', '-q')
  git('add', '-A')
  git('-c', 'user.name=Verification', '-c', 'user.email=verification@example.invalid', 'commit', '-qm', 'fixture')
  console.log('Initialised a git repository (needed by the rollback check).')
} catch {
  console.log('git not available — the rollback check will be less conclusive without it.')
}

console.log('\nVerification workspace ready:\n')
console.log(`  ${root}\n`)
console.log('Open that folder in the Extension Development Host, then work through')
console.log('MANUAL_VERIFICATION.md from the top.\n')
